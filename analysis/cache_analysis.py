#!/usr/bin/env python3
"""Measure whether the cache ideas are worth using.

This script reads the records generated by search_distribution.py and estimates
how much work each cache idea removes. It does not do the hash search itself.

The question is simple: which cache gives the biggest win in the final run?

There are two ideas to test:

1. Hot-zone cache: precompute hashes for a region that many requests overlap.
2. Exact-answer cache: keep a mapping from hash to answer and return it on a
   repeat.

For both methods, the metric is the number of hash calculations skipped. A
linear search from start to answer does about answer - start work for one
request.
"""

import argparse
import csv
import collections

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def load_records(path):
    # Read the output CSV produced by search_distribution.py.
    rows = []
    with open(path) as f:
        for r in csv.DictReader(f):
            rows.append({k: int(v) for k, v in r.items()})
    return rows


def total_search_work(rows):
    # Total work for a plain linear search in hash computations.
    return sum(r["offset"] for r in rows)


def exact_answer_cache(rows):
    """Measure the exact-answer cache.

    A repeat is any request whose (start, answer) pair shows up again. For those
    requests the cache can answer immediately and skip the whole search. The
    function returns the number of hits and the saved work.
    """
    seen = set()
    hits = 0
    work_removed = 0
    hits_by_priority = collections.Counter()
    for r in rows:
        key = (r["start"], r["answer"])
        if key in seen:
            hits += 1
            work_removed += r["offset"]     # Skip a full search for this request.
            hits_by_priority[r["priority"]] += 1
        else:
            seen.add(key)
    return hits, work_removed, hits_by_priority


def hot_zone_cache(rows, bins):
    """Measure the hot-zone cache.

    The value space is split into bins, and each request contributes the interval
    [start, answer]. The coverage count for a bin tells us how often many searches
    pass through that region. If a few bins are heavily covered, a hot-zone cache
    may help.
    """
    starts = np.array([r["start"] for r in rows], dtype=np.float64)
    answers = np.array([r["answer"] for r in rows], dtype=np.float64)
    lo = starts.min()
    hi = answers.max()
    span = max(hi - lo, 1.0)
    width = span / bins

    diff = np.zeros(bins + 1, dtype=np.int64)
    b0 = np.clip(((starts - lo) / width).astype(np.int64), 0, bins - 1)
    b1 = np.clip(((answers - lo) / width).astype(np.int64), 0, bins - 1)
    for i0, i1 in zip(b0, b1):
        diff[i0] += 1
        diff[i1 + 1] -= 1
    coverage = np.cumsum(diff[:-1])
    return coverage, lo, hi, width


def make_figure(rows, out_png, bins):
    coverage, lo, hi, width = hot_zone_cache(rows, bins)
    centers = lo + (np.arange(bins) + 0.5) * width

    # Count how often each answer repeats to show the exact-answer cache effect.
    key_counts = collections.Counter((r["start"], r["answer"]) for r in rows)
    repeat_hist = collections.Counter(key_counts.values())
    max_rep = max(repeat_hist)
    xs = list(range(1, max_rep + 1))
    ys = [repeat_hist.get(x, 0) for x in xs]

    fig, axes = plt.subplots(1, 2, figsize=(13, 5))

    # Left: overlap of ranges. A flat line means there is no strong hot zone.
    axes[0].plot(centers, coverage, lw=0.8, color="tab:orange")
    axes[0].set_title("Hot-zone test: interval overlap over the value space")
    axes[0].set_xlabel("absolute input value (bins)")
    axes[0].set_ylabel("number of search intervals that overlap")
    axes[0].ticklabel_format(axis="x", style="sci", scilimits=(0, 0))
    axes[0].axhline(coverage.mean(), color="black", lw=1.0, ls="--",
                    label=f"mean = {coverage.mean():.1f}")
    axes[0].legend()

    # Right: repeat count. Values greater than 1 show repeated answers.
    axes[1].bar(xs, ys, color="tab:blue", alpha=0.7)
    axes[1].set_title("Exact-answer test: how many hashes repeat")
    axes[1].set_xlabel("times a hash occurs")
    axes[1].set_ylabel("number of hashes")
    axes[1].set_yscale("log")

    fig.suptitle("Cache lever analysis for the final run parameters", fontsize=12)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(out_png, dpi=130)
    print("Saved figure:", out_png)


def main():
    p = argparse.ArgumentParser(description="Analyse the cache levers for the "
                                            "final run parameters.")
    p.add_argument("--records", default="analysis/final_records.csv")
    p.add_argument("--bins", type=int, default=200)
    p.add_argument("--out-png", default="analysis/cache_levers.png")
    args = p.parse_args()

    rows = load_records(args.records)
    n = len(rows)
    total_work = total_search_work(rows)

    hits, removed, hits_by_prio = exact_answer_cache(rows)
    coverage, lo, hi, width = hot_zone_cache(rows, args.bins)

    print(f"Records: {n}")
    print(f"Total linear search work (hash calculations): {total_work:,}")
    print()
    print("Exact-answer cache:")
    print(f"  cache hits (repeats): {hits} ({100 * hits / n:.1f} % of requests)")
    print(f"  work removed: {removed:,} ({100 * removed / total_work:.1f} % of total work)")
    print(f"  hits by priority: {dict(sorted(hits_by_prio.items()))}")
    print()
    print("Hot-zone cache:")
    print(f"  mean interval overlap per bin: {coverage.mean():.2f}")
    print(f"  max interval overlap per bin: {coverage.max()}")
    print(f"  bin width: {width:,.0f} values")
    busy = coverage.max() / max(coverage.mean(), 1e-9)
    print(f"  busiest bin over mean: {busy:.2f} x  (near 1 means no busy zone)")

    make_figure(rows, args.out_png, args.bins)


if __name__ == "__main__":
    main()
